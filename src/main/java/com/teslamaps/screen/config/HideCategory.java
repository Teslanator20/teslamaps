        b.toggle("Hide Clouds",
                () -> config.hideClouds, v -> config.hideClouds = v);
        b.toggle("Hide Fog", () -> config.noFog, v -> config.noFog = v);
        b.toggle("Nether Fog (Crimson Isle)", () -> config.noNetherFog, v -> config.noNetherFog = v);
